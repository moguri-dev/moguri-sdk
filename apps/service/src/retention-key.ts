import { randomBytes, randomUUID } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
import { AsyncEntry } from "@napi-rs/keyring";

export async function retentionKey(path: string, injected?: Buffer): Promise<{ key: Buffer; id: string }> {
  const db = new DatabaseSync(path);
  let id: string;
  try {
    const version = Number(db.prepare("PRAGMA user_version").get()?.user_version);
    if (version > 12) throw new Error("This state uses a newer schema. Upgrade Moguri; do not delete your data.");
    id = version >= 4 ? String(db.prepare("SELECT value FROM retention_metadata WHERE id='key_id'").get()?.value ?? "") : randomUUID();
    if (!id || id.length > 128) throw new Error("Retention key metadata is invalid. Preserve state and restore its original key metadata.");
  } finally { db.close(); }
  if (injected) {
    if (injected.byteLength !== 32) throw new Error("An injected retention key must have exactly 32 generated bytes.");
    return { key: Buffer.from(injected), id };
  }
  const entry = new AsyncEntry("dev.moguri.profile.default.retention", id, { linux: { store: "secret-service" } });
  const signal = AbortSignal.timeout(15_000);
  const existing = await entry.getPassword(signal);
  if (existing) {
    const key = Buffer.from(existing, "base64");
    if (key.byteLength !== 32 || key.toString("base64") !== existing) throw new Error("Moguri's retention key is invalid. Restore its OS-keychain entry; do not delete local state.");
    return { key, id };
  }
  const check = new DatabaseSync(path);
  try { if (Number(check.prepare("PRAGMA user_version").get()?.user_version) >= 4) throw new Error("Moguri's retention key is missing. Unlock or restore the OS keychain; local data was preserved."); }
  finally { check.close(); }
  const key = randomBytes(32);
  await entry.setPassword(key.toString("base64"), signal);
  return { key, id };
}
